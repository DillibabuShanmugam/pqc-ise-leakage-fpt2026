#!/usr/bin/env python3
"""Operand tables for the board firmware, six blocks.

Unprotected blocks carry the secret in one operand. Protected blocks split it
fresh every trace, so no single operand holds it. Both trios use the same secret
sequence, which lets the two be compared directly.
"""
import numpy as np, json, sys
Q = 3329
N = int(sys.argv[1]) if len(sys.argv) > 1 else 1000
rng = np.random.default_rng(31337)

s   = rng.integers(0, Q, N)            # secret coefficient, blocks 1 and 4
b   = rng.integers(0, Q, N)            # public coefficient
x   = rng.integers(0, Q, N)            # secret value, blocks 2 and 5
w   = rng.integers(0, 1 << 12, N)      # secret word, blocks 3 and 6
pw  = rng.integers(0, 1 << 12, N)      # public word

r1  = rng.integers(0, Q, N)
a0, a1 = (s + r1) % Q, (Q - r1) % Q                  # arithmetic split of s
r2  = rng.integers(0, Q, N)
s0, s1 = (x + r2) % Q, (Q - r2) % Q                  # arithmetic split of x
r3  = rng.integers(0, 1 << 12, N)
g0, g1 = w ^ r3, r3                                  # Boolean split of w
r4  = rng.integers(0, 1 << 12, N)
h1, h0 = pw ^ r4, r4                                 # Boolean split of the public word

tables = [("u_mont_s", s), ("u_mont_b", b), ("u_barr_x", x),
          ("u_and_s", w), ("u_and_b", pw),
          ("p_mul_a0", a0), ("p_mul_a1", a1), ("p_mul_b", b),
          ("p_red_s0", s0), ("p_red_s1", s1),
          ("p_and_a0", g0), ("p_and_a1", g1), ("p_and_b0", h0), ("p_and_b1", h1)]
with open("fw/operands_board.h", "w") as f:
    f.write("/* generated by gen_operands_board.py, do not edit */\n")
    for nm, v in tables:
        f.write(f"static const uint32_t {nm}[] = {{" + ",".join(str(int(t)) for t in v) + "};\n")
json.dump({"n": N, "secret_coeff": s.tolist(), "public_coeff": b.tolist(),
           "secret_value": x.tolist(), "secret_word": w.tolist(), "public_word": pw.tolist(),
           "mul_a0": a0.tolist(), "mul_a1": a1.tolist(),
           "red_s0": s0.tolist(), "red_s1": s1.tolist(),
           "and_a0": g0.tolist(), "and_a1": g1.tolist()},
          open("fw/operands_board.json", "w"))
print(f"board operands: N={N}, 6 blocks, secrets shared between the protected and unprotected trios")
